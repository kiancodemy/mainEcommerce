CREATE TABLE address
(
    id            BIGINT       NOT NULL,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    user_id       BIGINT       NOT NULL,
    province      VARCHAR(100) NOT NULL,
    city          VARCHAR(100) NOT NULL,
    postal_code   VARCHAR(10)  NOT NULL,
    phone_number  VARCHAR(11)  NOT NULL,
    static_number VARCHAR(11)  NOT NULL,
    description   VARCHAR(500),
    CONSTRAINT pk_address PRIMARY KEY (id)
);

CREATE TABLE books
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    title            VARCHAR(255)                            NOT NULL,
    status           BOOLEAN                                 NOT NULL,
    language         VARCHAR(255)                            NOT NULL,
    pages            INTEGER                                 NOT NULL,
    price            DECIMAL(12)                             NOT NULL,
    cost_price       DECIMAL(12)                             NOT NULL,
    stock            INTEGER                                 NOT NULL,
    publication_year INTEGER                                 NOT NULL,
    description      TEXT,
    publisher        VARCHAR(200),
    translator       VARCHAR(40),
    cover_image_url  VARCHAR(500),
    category_id      BIGINT,
    sub_category_id  BIGINT,
    CONSTRAINT pk_books PRIMARY KEY (id)
);

CREATE TABLE cart_items
(
    id         BIGINT  NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    cart_id    BIGINT  NOT NULL,
    book_id    BIGINT  NOT NULL,
    quantity   INTEGER NOT NULL,
    CONSTRAINT pk_cart_items PRIMARY KEY (id)
);

CREATE TABLE carts
(
    id         BIGINT                         NOT NULL,
    user_id    BIGINT                         NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_carts PRIMARY KEY (id)
);

CREATE TABLE category
(
    id         BIGINT       NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    name       VARCHAR(255) NOT NULL,
    status     BOOLEAN      NOT NULL,
    CONSTRAINT pk_category PRIMARY KEY (id)
);

CREATE TABLE "order"
(
    id             BIGINT       NOT NULL,
    created_at     TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at     TIMESTAMP(6) WITHOUT TIME ZONE,
    authority_code VARCHAR(255),
    user_id        BIGINT       NOT NULL,
    status         VARCHAR(255) NOT NULL,
    order_number   VARCHAR(255) NOT NULL,
    total_price    DECIMAL      NOT NULL,
    province       VARCHAR(100) NOT NULL,
    city           VARCHAR(100) NOT NULL,
    postal_code    VARCHAR(10)  NOT NULL,
    phone_number   VARCHAR(11)  NOT NULL,
    static_number  VARCHAR(11)  NOT NULL,
    description    VARCHAR(500),
    CONSTRAINT pk_order PRIMARY KEY (id)
);

CREATE TABLE order_item
(
    id       BIGINT       NOT NULL,
    title    VARCHAR(255) NOT NULL,
    book_id  BIGINT,
    price    DECIMAL(12)  NOT NULL,
    quantity INTEGER      NOT NULL,
    order_id BIGINT,
    CONSTRAINT pk_orderitem PRIMARY KEY (id)
);

CREATE TABLE password_reset_token
(
    id         INTEGER                        NOT NULL,
    token      VARCHAR(255)                   NOT NULL,
    "user-id"  BIGINT                         NOT NULL,
    expires_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    used       BOOLEAN                        NOT NULL,
    CONSTRAINT pk_passwordresettoken PRIMARY KEY (id)
);

CREATE TABLE refresh_token
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    user_id     BIGINT,
    token       VARCHAR(255)                            NOT NULL,
    family_id   UUID                                    NOT NULL,
    is_revoked  BOOLEAN                                 NOT NULL,
    expiry_date TIMESTAMP(6) WITHOUT TIME ZONE          NOT NULL,
    CONSTRAINT pk_refreshtoken PRIMARY KEY (id)
);

CREATE TABLE revchanges
(
    rev        BIGINT NOT NULL,
    entityname VARCHAR(255)
);

CREATE TABLE revinfo
(
    rev      BIGINT NOT NULL,
    revtstmp BIGINT,
    CONSTRAINT pk_revinfo PRIMARY KEY (rev)
);

CREATE TABLE sub_category
(
    id          BIGINT       NOT NULL,
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    name        VARCHAR(255) NOT NULL,
    status      BOOLEAN      NOT NULL,
    category_id BIGINT,
    CONSTRAINT pk_subcategory PRIMARY KEY (id)
);

CREATE TABLE users
(
    id         BIGINT       NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    name       VARCHAR(255),
    last_name  VARCHAR(255),
    email      VARCHAR(255) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    role       VARCHAR(255) NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

