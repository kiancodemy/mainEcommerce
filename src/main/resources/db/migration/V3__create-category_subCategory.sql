CREATE SEQUENCE IF NOT EXISTS category_seq START WITH 1 INCREMENT BY 50;

CREATE SEQUENCE IF NOT EXISTS sub_category_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE books
(
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title             VARCHAR(255)                             NOT NULL,
    description       VARCHAR(400),
    publisher         VARCHAR(200),
    translator        VARCHAR(40),
    language          VARCHAR(15)                              NOT NULL,
    publication_year  INTEGER,
    pages             INTEGER,
    price             DECIMAL(12)                              NOT NULL,
    cost_price        DECIMAL(12)                              NOT NULL,
    stock             INTEGER                                  NOT NULL,
    cover_image_url   VARCHAR(500),
    status            BOOLEAN                                  NOT NULL,
    "category-id"     INTEGER,
    "sub_category-id" INTEGER,
    created_at        TIMESTAMP(6) WITHOUT TIME ZONE           NOT NULL,
    CONSTRAINT pk_books PRIMARY KEY (id)
);

CREATE TABLE category
(
    id     INTEGER      NOT NULL,
    name   VARCHAR(255) NOT NULL,
    status BOOLEAN      NOT NULL,
    CONSTRAINT pk_category PRIMARY KEY (id)
);

CREATE TABLE sub_category
(
    id            INTEGER      NOT NULL,
    name          VARCHAR(255) NOT NULL,
    "category-id" INTEGER,
    CONSTRAINT pk_subcategory PRIMARY KEY (id)
);

